#!/usr/bin/env python3
"""Independently inspect literal fixtures and generate/check kernel test input."""
import argparse
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tests/conformance/vpt1_parser_vectors.json'
HEADER = ROOT / 'tests/conformance/vpt1_parser_vectors.h'


def inspect(vector):
    data = bytes.fromhex(vector['hex'])
    cap = vector['inner_cap']
    if vector['stage'] == 'datagram':
        magic, kind, flags, size, locator = struct.unpack('!4sBBHQ', data[:16])
        assert magic == b'VPT1' and flags == 0 and size == len(data) - 16
        assert 16 <= len(data) <= cap + 44
        assert (kind == 1 and locator == 0) or (kind in (2, 3) and locator != 0)
        counter = 0
        if kind in (1, 2):
            assert len(data) == {1: 224, 2: 176}[kind]
        else:
            counter, = struct.unpack('!Q', data[16:24])
            assert 44 <= len(data) and counter < 1048576
        return dict(kind=kind, locator=locator, counter=counter)
    subtype, flags, size = struct.unpack('!BBH', data[:4])
    assert flags == 0 and size == len(data) - 4 and len(data) <= cap + 4
    if subtype == 1:
        assert size >= 20 and data[4] == 0x45
        assert struct.unpack('!H', data[6:8])[0] == size
    else:
        assert size == {2: 32, 3: 32, 4: 32, 5: 32, 6: 16,
                        7: 16, 8: 48, 9: 48, 10: 32}[subtype]
    return dict(subtype=subtype, payload_len=size)


def render(vectors):
    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* Generated by tools/ay3_vectors.py; edit the literal JSON source. */']
    for index, vector in enumerate(vectors):
        data = bytes.fromhex(vector['hex'])
        lines.append(f'static const u8 vpt1_golden_{index}[] = {{')
        for start in range(0, len(data), 12):
            lines.append('\t' + ', '.join(f'0x{b:02x}' for b in data[start:start+12]) + ',')
        lines.extend(['};', ''])
    lines.append('static const struct vpt1_test_vector vpt1_vectors[] = {')
    for index, vector in enumerate(vectors):
        e = vector['expected']
        stage = 0 if vector['stage'] == 'datagram' else 1
        lines.extend(['\t{', f'\t\t.name = "{vector["name"]}",',
                      f'\t\t.data = vpt1_golden_{index},',
                      f'\t\t.len = sizeof(vpt1_golden_{index}),',
                      f'\t\t.stage = {stage}, .cap = {vector["inner_cap"]},',
                      f'\t\t.kind = {e.get("kind", 0)},',
                      f'\t\t.locator = 0x{e.get("locator", 0):016x}ULL,',
                      f'\t\t.counter = {e.get("counter", 0)}ULL,',
                      f'\t\t.subtype = {e.get("subtype", 0)},',
                      f'\t\t.payload_len = {e.get("payload_len", 0)},', '\t},'])
    lines.extend(['};', ''])
    return '\n'.join(lines).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    vectors = json.loads(SOURCE.read_text())['vectors']
    for vector in vectors:
        assert inspect(vector) == vector['expected'], vector['name']
    header = render(vectors)
    if args.check:
        if HEADER.read_text() != header:
            raise SystemExit('FAIL: generated header differs; run tools/ay3_vectors.py')
    else:
        HEADER.write_text(header)
    print(f'PASS: {len(vectors)} independent golden fixtures; header matches')


if __name__ == '__main__':
    main()
